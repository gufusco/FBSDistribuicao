def write_csv(path, fieldnames, rows):
    with path.open("w", newline="", encoding="utf-8") as file:
        writer = csv.DictWriter(file, fieldnames=fieldnames)
        writer.writeheader()
        writer.writerows(rows)


def generate_dev_corpus(destination=DATA):
    rows = []
    for label, templates in DEV_TEMPLATES.items():
        for index in range(200):
            template_index = index % len(templates)
            suffix = SUFFIXES[index // len(templates)]
            rows.append(
                {
                    "text": templates[template_index] + suffix,
                    "label": label,
                    "group": f"{label}_{template_index:02d}",
                }
            )
    write_csv(destination / "corpus_dev.csv", ["text", "label", "group"], rows)
    return rows


def generate_ood_corpus(destination=DATA):
    rows = [
        {"text": text, "label": label, "kind": "ood"}
        for label, phrases in OOD_EXAMPLES.items()
        for text in phrases
    ]
    rows.extend(
        {"text": text, "label": label, "kind": "regra"} for text, label in RULE_CASES
    )
    write_csv(destination / "corpus_ood.csv", ["text", "label", "kind"], rows)
    write_csv(
        destination / "corpus_ood_modelo.csv",
        ["text", "label"],
        [
            {
                "text": "Frase inédita com gíria ou abreviação",
                "label": "consultar_embarque",
            }
        ],
    )
    return rows


